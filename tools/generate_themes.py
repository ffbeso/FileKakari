"""Generate the bundled light/dark pairs and a local palette gallery (stdlib only)."""
from pathlib import Path
import colorsys
import html

ROOT = Path(__file__).resolve().parents[1]
THEMES = ROOT / "FileKakari" / "Themes"
PAIRS = [
    ("", "標準ブルー", 214, .78),
    ("Graphite", "グラファイト", 215, .16),
    ("Cappuccino", "カプチーノ", 28, .48),
    ("Forest", "フォレスト", 145, .48),
    ("Ocean", "オーシャン", 185, .65),
    ("Sakura", "サクラ", 340, .55),
    ("Lavender", "ラベンダー", 265, .55),
    ("Amber", "アンバー", 39, .80),
    ("Rose", "ローズ", 355, .66),
    ("Cyberpunk", "サイバーパンク", 285, .82),
]


def color(hue, saturation, lightness):
    rgb = colorsys.hls_to_rgb(hue / 360, lightness, saturation)
    return "#" + "".join(f"{round(c * 255):02X}" for c in rgb)


def palette(hue, saturation, dark):
    def c(light, night, sat=None):
        return color(hue, saturation if sat is None else sat, night if dark else light)

    # Surfaces carry a low-saturation tint; accent and selection keep the pair's hue.
    p = {
        "AppBackground": c(.955, .090, .12),
        "PanelBackground": c(.990, .125, .10),
        "ControlBackground": c(.980, .160, .12),
        "ControlHover": c(.920, .220, .20),
        "ControlPressed": c(.855, .285, .25),
        "ControlDisabled": c(.940, .145, .07),
        "HeaderBackground": c(.940, .155, .12),
        "HeaderHover": c(.895, .215, .18),
        "HeaderGrip": c(.590, .440, .12),
        "HeaderGripHover": c(.430, .600, .18),
        "RowBackground": c(.990, .125, .10),
        "RowHover": c(.955, .190, .18),
        "TabBackground": c(.890, .085, .13),
        "TabSelectedBackground": c(.990, .180, .10),
        "TabHoverBackground": c(.950, .235, .17),
        "TabSeparator": c(.620, .440, .12),
        "Text": c(.130, .940, .12),
        "SubtleText": c(.350, .720, .12),
        "Border": c(.720, .350, .10),
        "GridLine": c(.900, .215, .08),
        "SelectionBackground": c(.865, .285, min(saturation, .50)),
        "SelectionInactiveBackground": c(.895, .235, .10),
        "SelectionText": c(.105, .970, .10),
        "FolderIcon": "#A36A08" if not dark else "#F0BF65",
        "FileIcon": c(.400, .720),
        "ScrollBarTrack": c(.950, .115, .08),
        "ScrollBarThumb": c(.650, .400, .10),
        "ScrollBarThumbHover": c(.510, .530, .14),
        "ScrollBarThumbPressed": c(.400, .650, .18),
        "StatusBarBackground": c(.940, .105, .12),
        "MenuIconColumnBackground": c(.980, .160, .12),
        "ActivePaneBorder": c(.470, .610, min(saturation, .45)),
        "InactivePaneBorder": c(.780, .310, .10),
        "ActivePaneAccent": c(.380, .710),
        "InactivePaneAccent": c(.500, .570, .12),
    }
    return p


def write_theme(name, label, p):
    lines = [
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        f'    <!-- {label}; generated by tools/generate_themes.py -->',
    ]
    lines += [f'    <Color x:Key="{key}Color">{value}</Color>' for key, value in p.items()]
    lines += [f'    <Color x:Key="SubTabOverflowFadeTransparentColor">#00{p["PanelBackground"][1:]}</Color>', ""]
    lines += [f'    <SolidColorBrush x:Key="{key}Brush" Color="{{DynamicResource {key}Color}}" />' for key in p]
    lines += ["</ResourceDictionary>", ""]
    (THEMES / name).write_text("\n".join(lines), encoding="utf-8")


def sample(label, p):
    style = ";".join(f"--{k}:{v}" for k, v in p.items())
    return f'''<article style="{style}"><h3>{html.escape(label)}</h3>
<div class="tabs"><span>Documents</span><b>Pictures</b></div>
<div class="toolbar">‹ &nbsp; › &nbsp; Pictures <span>⌕</span></div>
<div class="columns">名前 <span>種類</span></div>
<div class="row"><i>▰</i>旅行 <span>フォルダー</span></div>
<div class="row selected">海辺.jpg <span>JPEG</span></div>
<div class="row">森の散歩.png <span>PNG</span></div>
<div class="row inactive">カフェ.jpg <span>非アクティブ選択</span></div>
<footer>4 項目 · 1 項目を選択 <em>サブタブの目印 ━</em></footer></article>'''


def main():
    sections = []
    for name, label, hue, saturation in PAIRS:
        samples = []
        for dark in (False, True):
            mode = "Dark" if dark else "Light"
            p = palette(hue, saturation, dark)
            write_theme(f"{name}{mode}Theme.xaml", f"{label} / {mode}", p)
            # Keep legacy bundled filenames compatible. Existing user copies are never overwritten.
            legacy = {("Graphite", True): "Gray", ("Cappuccino", True): "Cappuccino",
                      ("Forest", False): "Forest", ("Cyberpunk", True): "Cyberpunk"}.get((name, dark))
            if legacy:
                write_theme(f"{legacy}Theme.xaml", f"{label} / {mode} (legacy filename)", p)
            samples.append(sample(mode, p))
        sections.append(f'<section><h2>{label}</h2><div class="pair">{"".join(samples)}</div></section>')
    gallery = '''<!doctype html><html lang="ja"><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>FileKakari — 10組のテーマ</title><style>
*{box-sizing:border-box}body{margin:0;padding:40px;background:#e8eaee;color:#202632;font:14px "Yu Gothic UI",sans-serif}
main{max-width:1080px;margin:auto}h1{font-size:30px}h2{margin-top:36px;font-size:20px}h3{margin:0;padding:16px;color:var(--Text);font-size:16px}
.pair{display:grid;grid-template-columns:1fr 1fr;gap:20px}article{background:var(--AppBackground);color:var(--Text);border:1px solid var(--Border);border-radius:10px;overflow:hidden}
.tabs{display:flex;gap:3px;padding:0 12px;background:var(--AppBackground)}.tabs>*{padding:9px 18px;background:var(--TabBackground);border:1px solid var(--TabSeparator)}
.tabs b{background:var(--TabSelectedBackground);border-bottom:3px solid var(--ActivePaneAccent)}
.toolbar{padding:12px;background:var(--ControlBackground);border-block:1px solid var(--Border)}span{float:right;color:var(--SubtleText)}
.columns{padding:8px 16px;background:var(--HeaderBackground);color:var(--SubtleText)}.row{padding:10px 16px;background:var(--RowBackground);border-bottom:1px solid var(--GridLine)}
.row i{color:var(--FolderIcon);font-style:normal;margin-right:8px}.row.selected{background:var(--SelectionBackground);color:var(--SelectionText)}
.row.inactive{background:var(--SelectionInactiveBackground);color:var(--SelectionText)}.selected span,.inactive span{color:inherit}
footer{padding:12px;background:var(--StatusBarBackground);color:var(--SubtleText);font-size:12px}em{float:right;font-style:normal}
@media(max-width:700px){body{padding:20px}.pair{grid-template-columns:1fr}}
</style><main><h1>FileKakari · 10組のテーマ</h1><p>同じ色相のライト／ダーク。配色見本です。実際のWPF画面のスクリーンショットではありません。</p>'''
    (ROOT / "docs" / "theme-gallery.html").write_text(gallery + "".join(sections) + "</main></html>\n", encoding="utf-8")


if __name__ == "__main__":
    main()
